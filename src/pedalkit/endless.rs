//! `endless_patch!`: turns a `Pedal` into a complete Endless patch (the C
//! entry points, the header the firmware reads, the panic handler, and an
//! `ENTRY` table the host demo drives).
//!
//! ```ignore
//! endless_patch!(kit = crate::pedalkit, pedal = crate::patch::Patch);
//! endless_patch!(kit = crate::pedalkit, pedal = crate::superpedal::SuperPedal, memory = working);
//! ```
//! The default memory is a static `.bss` pool of `Pedal::POOL` floats;
//! `memory = working` leaves the pool to the pedal's `attach` (the firmware's
//! working buffer). Paths are absolute so the macro works from any module.

#[macro_export]
macro_rules! endless_patch {
    (kit = $($kit:ident)::+, pedal = $($pedal:ident)::+) => {
        $crate::endless_patch!(@impl [$($kit)::+] [$($pedal)::+] static);
    };
    (kit = $($kit:ident)::+, pedal = $($pedal:ident)::+, memory = working) => {
        $crate::endless_patch!(@impl [$($kit)::+] [$($pedal)::+] working);
    };
    (@mem static) => {{
        static POOL_MEM: kit::global::Global<[f32; <P as kit::pedal::Pedal>::POOL]> =
            kit::global::Global::new([0.0; <P as kit::pedal::Pedal>::POOL]);
        kit::pedal::Memory::Static(POOL_MEM.get().as_mut_ptr(), <P as kit::pedal::Pedal>::POOL)
    }};
    (@mem working) => {
        kit::pedal::Memory::Working
    };
    (@impl [$($kit:tt)*] [$($pedal:tt)*] $mem:ident) => {
        /// The firmware's C entry points (generated by `endless_patch!`).
        pub mod entry {
            use $($kit)* as kit;
            use kit::abi::*;
            use kit::pedal::{Runner, write_c_str};

            type P = $($pedal)*;
            type R = Runner<P>;
            static RUNNER: kit::global::Global<R> = kit::global::Global::new(R::NEW);

            fn runner() -> &'static mut R {
                RUNNER.get()
            }

            pub unsafe extern "C" fn patch_init(env: *const PatchEnv) {
                if env.is_null() || unsafe { (*env).abi_version } != PATCH_ABI_VERSION as u32 {
                    return;
                }
                runner().init($crate::endless_patch!(@mem $mem));
            }

            pub unsafe extern "C" fn update_buffers(
                _: *const PatchEnv,
                left: *mut f32,
                right: *mut f32,
                samples: i32,
            ) -> f32 {
                let Ok(n) = usize::try_from(samples) else { return 0.0 };
                if left.is_null() || right.is_null() || n == 0 {
                    return 0.0;
                }
                // SAFETY: the firmware passes two buffers of `samples` floats.
                let (l, r) =
                    unsafe { (core::slice::from_raw_parts_mut(left, n), core::slice::from_raw_parts_mut(right, n)) };
                runner().update(l, r);
                0.0
            }

            pub unsafe extern "C" fn set_buffer(_: *const PatchEnv, buffer: *mut f32) {
                runner().set_buffer(buffer, WORKING_BUFFER_SIZE as usize);
            }

            pub unsafe extern "C" fn get_buffer_size(_: *const PatchEnv) -> i32 {
                WORKING_BUFFER_SIZE
            }

            pub unsafe extern "C" fn get_param_min(_: *const PatchEnv, _: i32) -> f32 {
                0.0
            }

            pub unsafe extern "C" fn get_param_max(_: *const PatchEnv, _: i32) -> f32 {
                1.0
            }

            pub unsafe extern "C" fn get_param_default(_: *const PatchEnv, idx: i32) -> f32 {
                R::param(idx).map_or(0.0, |p| p.1)
            }

            pub unsafe extern "C" fn is_param_enabled(_: *const PatchEnv, idx: i32, source_id: i32) -> u8 {
                // Knobs only (source 0), like the SDK wrapper.
                (source_id == 0 && R::param(idx).is_some()) as u8
            }

            pub unsafe extern "C" fn get_param_name(_: *const PatchEnv, idx: i32, out: *mut u8, len: usize) {
                unsafe { write_c_str(R::param(idx).map_or("", |p| p.0), out, len) }
            }

            pub unsafe extern "C" fn get_param_unit(_: *const PatchEnv, _: i32, out: *mut u8, len: usize) {
                unsafe { write_c_str("", out, len) }
            }

            pub unsafe extern "C" fn set_param(_: *const PatchEnv, idx: i32, value: f32) {
                runner().set_param(idx, value);
            }

            pub unsafe extern "C" fn special_action(_: *const PatchEnv, idx: i32) {
                runner().action(idx);
            }

            pub unsafe extern "C" fn get_state_idx(_: *const PatchEnv) -> i32 {
                runner().led() as i32
            }

            #[cfg(target_os = "none")]
            unsafe extern "C" {
                static __patch_bss_start: u8;
                static patch_image_size: u8;
                static patch_bss_size: u8;
            }

            /// The header the firmware reads from the image's first bytes.
            #[cfg(target_os = "none")]
            #[unsafe(no_mangle)]
            #[unsafe(link_section = ".patch_header")]
            #[used]
            pub static patch_header: PatchHeader = PatchHeader {
                magic: PATCH_MAGIC,
                abi_version: PATCH_ABI_VERSION,
                flags: PATCH_FLAG_NONE,
                init: patch_init,
                agent_update_buffers: update_buffers,
                agent_set_buffer: set_buffer,
                agent_get_buffer_size: get_buffer_size,
                agent_get_param_min: get_param_min,
                agent_get_param_max: get_param_max,
                agent_get_param_default: get_param_default,
                agent_is_param_enabled: is_param_enabled,
                agent_get_param_name: get_param_name,
                agent_get_param_unit: get_param_unit,
                agent_set_param: set_param,
                agent_special_action: special_action,
                agent_get_state_idx: get_state_idx,
                image_size: &raw const patch_image_size,
                bss_begin: &raw const __patch_bss_start,
                bss_size: &raw const patch_bss_size,
                reserved: [0; 16],
            };

            #[cfg(target_os = "none")]
            #[panic_handler]
            fn panic(_: &core::panic::PanicInfo) -> ! {
                loop {
                    core::hint::spin_loop();
                }
            }

            /// The pedal itself, for host-side analysis.
            #[cfg(not(target_os = "none"))]
            #[allow(dead_code)]
            pub fn pedal() -> &'static mut P {
                runner().pedal()
            }

            /// The entry points as a table, for the host demo.
            #[cfg(not(target_os = "none"))]
            pub const ENTRY: kit::host::Entry = kit::host::Entry {
                patch_init,
                update_buffers,
                set_buffer,
                get_param_default,
                set_param,
                special_action,
                get_state_idx,
                get_param_name,
                pool_used: || runner().pool_used(),
            };
        }
    };
}
